import * as NodeServices from "@effect/platform-node/NodeServices";
import { assert, it } from "@effect/vitest";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";

import {
  cliproxyDirectories,
  renderCliProxyConfig,
  writeCliProxyConfig,
} from "./CliProxyConfig.ts";

it("renders a deterministic loopback-only config with everything q1code fixes", () => {
  const text = renderCliProxyConfig({
    port: 8317,
    authDir: "/home/mic/.q1code/cliproxy/auths",
    apiKey: "key-1",
    managementSecret: 'sec"ret',
    routingStrategy: "fill-first",
  });
  assert.equal(
    text,
    [
      "# Generated by q1code. Overwritten on every sidecar start; edit fork.json instead.",
      'host: "127.0.0.1"',
      "port: 8317",
      'auth-dir: "/home/mic/.q1code/cliproxy/auths"',
      "api-keys:",
      '  - "key-1"',
      "remote-management:",
      "  allow-remote: false",
      '  secret-key: "sec\\"ret"',
      "  disable-control-panel: true",
      "  disable-auto-update-panel: true",
      "routing:",
      '  strategy: "fill-first"',
      "  session-affinity: false",
      "quota-exceeded:",
      "  switch-project: true",
      "  switch-preview-model: true",
      "request-retry: 3",
      "debug: false",
      "usage-statistics-enabled: false",
      "logging-to-file: false",
      "request-log: false",
      "ws-auth: true",
      "plugins:",
      "  enabled: false",
      "",
    ].join("\n"),
  );
  assert.equal(
    renderCliProxyConfig({ authDir: "/a", apiKey: "k", managementSecret: "s" }),
    renderCliProxyConfig({ authDir: "/a", apiKey: "k", managementSecret: "s" }),
  );
});

it("defaults the port and routing strategy", () => {
  const text = renderCliProxyConfig({ authDir: "/a", apiKey: "k", managementSecret: "s" });
  assert.include(text, "\nport: 8317\n");
  assert.include(text, '\n  strategy: "round-robin"\n');
});

it.layer(NodeServices.layer)("cliproxy config files", (it) => {
  it.effect("lays the sidecar out under <baseDir>/cliproxy", () =>
    Effect.gen(function* () {
      const path = yield* Path.Path;
      const directories = cliproxyDirectories("/base", path);
      assert.equal(directories.rootDir, path.join("/base", "cliproxy"));
      assert.equal(directories.authsDir, path.join("/base", "cliproxy", "auths"));
      assert.equal(directories.binDir, path.join("/base", "cliproxy", "bin"));
      assert.equal(directories.codexHomeDir, path.join("/base", "cliproxy", "codex-home"));
      assert.equal(directories.configPath, path.join("/base", "cliproxy", "config.yaml"));
      assert.equal(directories.tombstonesPath, path.join("/base", "cliproxy", "tombstones.json"));
    }),
  );

  it.effect("writes the config atomically with owner-only permissions", () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const directory = yield* fs.makeTempDirectoryScoped({ prefix: "q1code-cliproxy-config-" });
      const configPath = path.join(directory, "nested", "config.yaml");
      yield* writeCliProxyConfig(configPath, "port: 1\n");
      yield* writeCliProxyConfig(configPath, "port: 2\n");
      assert.equal(yield* fs.readFileString(configPath), "port: 2\n");
      const stat = yield* fs.stat(configPath);
      assert.equal(stat.mode & 0o777, 0o600);
      const leftovers = yield* fs.readDirectory(path.dirname(configPath));
      assert.deepEqual(leftovers, ["config.yaml"]);
    }).pipe(Effect.scoped),
  );
});
